#ifndef BSW_SERVICE_DIAGNOSTICS_UDS_H_
#define BSW_SERVICE_DIAGNOSTICS_UDS_H_

#include <stdint.h>
#include <stdbool.h>

/*********************************************************************************************************************/
/*------------------------------------------------------Macros-------------------------------------------------------*/
/*********************************************************************************************************************/
#define MAX_PERIODIC_TASKS 5

/*********************************************************************************************************************/
/*--------------------------------------------------Data Structures--------------------------------------------------*/
/*********************************************************************************************************************/
typedef enum {
    UDS_DID_TOF_SENSOR = 0x1000,
    UDS_DID_LEFT_ULTRASONIC_SENSOR = 0x2000,
    UDS_DID_RIGHT_ULTRASONIC_SENSOR = 0x2001,
    UDS_DID_BACK_ULTRASONIC_SENSOR = 0x2002,
} UDS_DID;

typedef struct {
    uint16_t did;
    uint16_t intervalMs;
    uint8_t isActive;
    volatile uint32_t timer;
} PeriodicTransmission;

/*********************************************************************************************************************/
/*-------------------------------------------------Global variables--------------------------------------------------*/
/*********************************************************************************************************************/
extern PeriodicTransmission g_periodicTasks[MAX_PERIODIC_TASKS];

/*********************************************************************************************************************/
/*-----------------------------------------------Function Prototypes-------------------------------------------------*/
/*********************************************************************************************************************/
void UDS_HandleMessage(const uint8_t* data, uint16_t length);
void sendNegativeResponse(uint8_t sid, uint8_t nrc);
void UDS_HandlePeriodicTransmission(void);

#endif /* BSW_SERVICE_DIAGNOSTICS_UDS_H_ */
